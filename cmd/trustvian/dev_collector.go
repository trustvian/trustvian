// writeCollectorConfig renders the document into dev's state directory.
func writeCollectorConfig(path string, data collectorConfigData) error {
	var rendered strings.Builder
	if err := collectorTemplate.Execute(&rendered, data); err != nil {
		return fmt.Errorf("rendering the collector configuration: %w", err)
	}
	if err := os.WriteFile(path, []byte(rendered.String()), devStateFileMode); err != nil {
		return fmt.Errorf("writing the collector configuration: %w", err)
	}
	return nil
}

// validateCollectorScalar refuses a value that cannot go into the document
// safely.
//
// Nothing substitutes a string yet: every value slice 2b writes is a port. It
// exists now because slice 3 substitutes a run id and a behavioral profile —
// caller-supplied strings — and the rule for them should be written while the
// reason is in view rather than discovered by a quoting bug.
//
// The template quotes every string it substitutes, so the rule is the one that
// keeps a *double-quoted* YAML scalar intact: no quote, no backslash, no line
// break, no control character. An earlier version enumerated plain-scalar
// hazards instead and refused every colon — which rejected `git:43af19c`, the
// candidate identity format slice 3 derives from a commit. Quoting the scalar
// and checking a narrow rule is both safer and less surprising than guessing
// which punctuation YAML minds.
//
// Refused, not escaped. These are identity values: a run id rewritten to be
// representable is not the run id the control plane knows, and the Collector
// would then point at a run that does not exist. Task 054 applies the same rule
// to behavioral identity for the same reason.
func validateCollectorScalar(field, value string) error {
	if value == "" {
		return fmt.Errorf("%s is empty", field)
	}
	if strings.TrimSpace(value) != value {
		return fmt.Errorf("%s has leading or trailing whitespace: %q", field, value)
	}
	if strings.ContainsAny(value, "\"\\") {
		return fmt.Errorf(
			"%s contains a quote or backslash, which would break the generated "+
				"configuration: %q", field, value)
	}
	for _, r := range value {
		// Control characters include the line breaks that would let a value
		// introduce a key of its own.
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf(
				"%s contains a control character, which would change the "+
					"structure of the generated configuration: %q", field, value)
		}
	}
	return nil
}

