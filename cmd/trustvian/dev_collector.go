// reservePorts picks n distinct free loopback ports.
//
// Every listener is open at once before any port is reported, then all are
// closed. Choosing them one at a time would let a later selection return an
// earlier one's port, because nothing holds it in between — a collision that
// then shows up as "the Collector exited during startup" rather than as itself.
// The demo prototype hit exactly this and allocates in a batch for the same
// reason.
//
// Still advisory: between closing and the Collector binding, another process can
// take one. That is what startCollector's retry is for.
func reservePorts(n int) ([]int, error) {
	listeners := make([]net.Listener, 0, n)
	defer func() {
		for _, listener := range listeners {
			listener.Close()
		}
	}()

	ports := make([]int, 0, n)
	seen := make(map[int]bool, n)
	for range n {
		listener, err := net.Listen("tcp", "127.0.0.1:0")
		if err != nil {
			return nil, err
		}
		listeners = append(listeners, listener)

		port := listener.Addr().(*net.TCPAddr).Port
		if seen[port] {
			// Not reachable while every listener is open, and asserted rather
			// than assumed: two identical ports would make the Collector fight
			// itself for one of them.
			return nil, errors.New("the OS returned one port twice")
		}
		seen[port] = true
		ports = append(ports, port)
	}
	return ports, nil
}

// probeHealth reports whether the processor's /livez answers.
//
// A fresh client per probe with a short timeout, and no keep-alive: this runs a
// few dozen times at startup and never again, so connection reuse would only
// keep a socket open to a process about to be signalled.
func probeHealth(port int) bool {
	client := &http.Client{Timeout: collectorProbeTimeout}
	defer client.CloseIdleConnections()

	url := fmt.Sprintf("http://127.0.0.1:%d/livez", port)
	response, err := client.Get(url)
	if err != nil {
		return false
	}
	defer response.Body.Close()
	return response.StatusCode == http.StatusOK
}

// portAccepts reports whether something is listening.
//
// A dial and an immediate close. Not an OTLP request: sending one would put a
// span into the pipeline that no run asked for, and this only needs to know
// whether the socket exists.
func portAccepts(port int) bool {
	conn, err := net.DialTimeout("tcp",
		fmt.Sprintf("127.0.0.1:%d", port), collectorProbeTimeout)
	if err != nil {
		return false
	}
	conn.Close()
	return true
}
